/**
 * Builds a deterministic AIS track that ends at the vessel's current position.
 * `hours` of history at 30-minute reporting intervals.
 */
export function buildTrack(vessel: Vessel, hours = 12): VesselTrack {
  const rnd = seededRandom(Number(vessel.mmsi.slice(-6)));
  const steps = hours * 2;
  const points: TrackPoint[] = [];
  let position: LatLng = vessel.position;
  const reverse = (vessel.courseDeg + 180) % 360;

  for (let i = 0; i < steps; i += 1) {
    const jitter = (rnd() - 0.5) * 26;
    const legKm = Math.max(0.25, (vessel.speedKn * 1.852) / 2) * (0.75 + rnd() * 0.5);
    position = project(position, (reverse + jitter + 360) % 360, legKm);
    points.push({
      position,
      timestamp: isoOffset(-30 * (i + 1)),
      speedKn: round(Math.max(0, vessel.speedKn + (rnd() - 0.5) * 3.4), 1),
      courseDeg: round((vessel.courseDeg + jitter + 360) % 360, 0)
    });
  }

  return {
    mmsi: vessel.mmsi,
    name: vessel.name,
    points: [
      ...points.reverse(),
      { position: vessel.position, timestamp: vessel.timestamp, speedKn: vessel.speedKn, courseDeg: vessel.courseDeg }
    ]
  };
}

export const VESSEL_TRACKS: Record<string, VesselTrack> = VESSELS.reduce(
  (acc, v) => ({ ...acc, [v.mmsi]: buildTrack(v) }),
  {} as Record<string, VesselTrack>
);
